-- 회원
CREATE TABLE users (
  user_id UUID DEFAULT gen_random_uuid() NOT NULL PRIMARY KEY,
  username VARCHAR(30) NOT NULL,
  nickname VARCHAR(20) NOT NULL,
  email TEXT,
  avatar_url TEXT,
  bio TEXT,
  role VARCHAR(20) DEFAULT 'USER' NOT NULL,
  account_status VARCHAR(30) DEFAULT 'ACTIVE' NOT NULL,
  restriction_reason TEXT,
  visibility_status VARCHAR(20) DEFAULT 'PUBLIC' NOT NULL,
  hidden_reason TEXT,
  onboarding_completed_at TIMESTAMPTZ DEFAULT now() NOT NULL,
  profile_links JSONB DEFAULT '{}'::jsonb NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT now() NOT NULL,
  CHECK (role IN ('USER','ADMIN')),
  CHECK (account_status IN ('ACTIVE','REGISTRATION_RESTRICTED','SUSPENDED')),
  CHECK (visibility_status IN ('PUBLIC','TEMP_HIDDEN','HIDDEN')),
  CHECK (username IS NULL OR username ~ '^[A-Za-z0-9._]{1,30}$'),
  CHECK (nickname IS NULL OR (char_length(nickname) BETWEEN 2 AND 20 AND nickname = btrim(nickname))),
  CHECK (jsonb_typeof(profile_links) = 'object')
);
COMMENT ON TABLE users IS '회원';
COMMENT ON COLUMN users.user_id IS '회원 고유 번호';
COMMENT ON COLUMN users.username IS '공개 아이디';
COMMENT ON COLUMN users.nickname IS '닉네임';
COMMENT ON COLUMN users.email IS '비공개 이메일';
COMMENT ON COLUMN users.avatar_url IS '프로필 이미지 주소';
COMMENT ON COLUMN users.bio IS '한 줄 소개';
COMMENT ON COLUMN users.role IS '권한';
COMMENT ON COLUMN users.account_status IS '계정 상태';
COMMENT ON COLUMN users.restriction_reason IS '계정 제한 사유';
COMMENT ON COLUMN users.visibility_status IS '공개 상태';
COMMENT ON COLUMN users.hidden_reason IS '비공개 사유';
COMMENT ON COLUMN users.onboarding_completed_at IS '온보딩 완료 일시';
COMMENT ON COLUMN users.profile_links IS '외부 링크 모음';

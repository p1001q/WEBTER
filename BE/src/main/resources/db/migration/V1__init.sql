CREATE TABLE reports (
  report_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  reporter_id UUID,
  target_type VARCHAR(20) NOT NULL,
  target_key TEXT NOT NULL,
  target_service_id BIGINT,
  target_review_id BIGINT,
  target_review_reply_id UUID,
  target_comment_id BIGINT,
  target_user_id UUID,
  reason_code VARCHAR(40) NOT NULL,
  detail TEXT,
  status VARCHAR(20) DEFAULT 'OPEN' NOT NULL,
  reviewed_by UUID,
  reviewed_at TIMESTAMPTZ,
  resolution_note TEXT,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
  CHECK (target_type IN ('SERVICE','REVIEW','REVIEW_REPLY','COMMENT','PROFILE')),
  CHECK (num_nonnulls(target_service_id, target_review_id, target_review_reply_id, target_comment_id, target_user_id) <= 1),
  CHECK ((target_service_id IS NULL OR (target_type = 'SERVICE' AND target_key = target_service_id::text)) AND (target_review_id IS NULL OR (target_type = 'REVIEW' AND target_key = target_review_id::text)) AND (target_review_reply_id IS NULL OR (target_type = 'REVIEW_REPLY' AND target_key = target_review_reply_id::text)) AND (target_comment_id IS NULL OR (target_type = 'COMMENT' AND target_key = target_comment_id::text)) AND (target_user_id IS NULL OR (target_type = 'PROFILE' AND target_key = target_user_id::text))),
  CHECK (status IN ('OPEN','RESOLVED','DISMISSED')),
  UNIQUE (reporter_id, target_type, target_key),
  FOREIGN KEY (reporter_id) REFERENCES users (user_id) ON DELETE SET NULL,
  FOREIGN KEY (target_service_id) REFERENCES services (service_id) ON DELETE SET NULL,
  FOREIGN KEY (target_review_id) REFERENCES reviews (review_id) ON DELETE SET NULL,
  FOREIGN KEY (target_review_reply_id) REFERENCES reviews (reply_id) ON DELETE SET NULL ON UPDATE SET NULL,
  FOREIGN KEY (target_comment_id) REFERENCES service_comments (comment_id) ON DELETE SET NULL,
  FOREIGN KEY (target_user_id) REFERENCES users (user_id) ON DELETE SET NULL,
  FOREIGN KEY (reviewed_by) REFERENCES users (user_id) ON DELETE SET NULL
);

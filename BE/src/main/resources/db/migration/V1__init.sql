CREATE TABLE services (
  service_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  owner_id UUID NOT NULL,
  name VARCHAR(30) NOT NULL,
  tagline VARCHAR(60) NOT NULL,
  description_markdown TEXT,
  service_url TEXT NOT NULL,
  canonical_url TEXT NOT NULL,
  github_url TEXT,
  project_type VARCHAR(20) NOT NULL,
  price_type VARCHAR(20) NOT NULL,
  registrant_type VARCHAR(20) NOT NULL,
  team_name TEXT,
  availability_status VARCHAR(20) DEFAULT 'AVAILABLE' NOT NULL,
  unavailable_reason VARCHAR(60),
  visibility_status VARCHAR(20) DEFAULT 'PUBLIC' NOT NULL,
  hidden_reason TEXT,
  icon_url TEXT,
  thumbnail_url TEXT,
  preview_ratio VARCHAR(10) DEFAULT '16:9' NOT NULL,
  preview_fit VARCHAR(10) DEFAULT 'COVER' NOT NULL,
  allow_guest_reviews BOOLEAN DEFAULT FALSE NOT NULL,
  allow_anonymous_reviews BOOLEAN DEFAULT FALSE NOT NULL,
  allow_anonymous_comments BOOLEAN DEFAULT FALSE NOT NULL,
  registration_policy_id BIGINT NOT NULL,
  registration_agreed_at TIMESTAMPTZ NOT NULL,
  url_checked_at TIMESTAMPTZ,
  device_codes JSONB NOT NULL,
  language_codes JSONB DEFAULT '["KO"]'::jsonb NOT NULL,
  preview_images JSONB DEFAULT '[]'::jsonb NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT now() NOT NULL,
  UNIQUE (canonical_url),
  CHECK (service_url ~ '^https://'),
  CHECK (project_type IN ('TOY','SIDE','COMMERCIAL')),
  CHECK (price_type IN ('FREE','PAID','FREEMIUM')),
  CHECK (registrant_type IN ('INDIVIDUAL','TEAM')),
  CHECK ((registrant_type = 'TEAM' AND team_name IS NOT NULL AND btrim(team_name) <> '') OR (registrant_type = 'INDIVIDUAL' AND team_name IS NULL)),
  CHECK (availability_status IN ('AVAILABLE','UNAVAILABLE')),
  CHECK (availability_status <> 'UNAVAILABLE' OR (unavailable_reason IS NOT NULL AND btrim(unavailable_reason) <> '')),
  CHECK (visibility_status IN ('PUBLIC','TEMP_HIDDEN','HIDDEN')),
  CHECK (preview_ratio IN ('16:9','9:16')),
  CHECK (preview_fit IN ('COVER','CONTAIN')),
  CHECK (description_markdown IS NULL OR char_length(description_markdown) <= 5000),
  CHECK (jsonb_typeof(preview_images) = 'array' AND jsonb_array_length(preview_images) <= 8),
  CHECK (jsonb_typeof(device_codes) = 'array' AND jsonb_array_length(device_codes) BETWEEN 1 AND 2 AND device_codes <@ '["PC","MOBILE"]'::jsonb),
  CHECK (jsonb_typeof(language_codes) = 'array' AND jsonb_array_length(language_codes) <= 2 AND language_codes <@ '["KO","EN"]'::jsonb),
  FOREIGN KEY (owner_id) REFERENCES users (user_id) ON DELETE CASCADE,
  FOREIGN KEY (registration_policy_id) REFERENCES policy_documents (policy_document_id) ON DELETE RESTRICT
);

-- 서비스 리뷰·평가
CREATE TABLE reviews (
  review_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
  service_id BIGINT NOT NULL,
  author_id UUID,
  author_kind VARCHAR(10) NOT NULL,
  guest_ip_hmac TEXT,
  guest_ip_display TEXT,
  rating VARCHAR(20) DEFAULT 'NONE' NOT NULL,
  content VARCHAR(500) NOT NULL,
  is_anonymous BOOLEAN DEFAULT FALSE NOT NULL,
  is_creator_review BOOLEAN DEFAULT FALSE NOT NULL,
  visibility_status VARCHAR(20) DEFAULT 'PUBLIC' NOT NULL,
  hidden_reason TEXT,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT now() NOT NULL,
  reply_id UUID,
  reply_author_id UUID,
  reply_content VARCHAR(500),
  reply_visibility_status VARCHAR(20),
  reply_hidden_reason TEXT,
  reply_created_at TIMESTAMPTZ,
  reply_updated_at TIMESTAMPTZ,
  CHECK (author_kind IN ('MEMBER','GUEST')),
  CHECK (rating IN ('RECOMMEND','NOT_RECOMMEND','NONE')),
  CHECK ((author_kind = 'GUEST' AND author_id IS NULL AND guest_ip_hmac IS NOT NULL AND rating = 'NONE' AND is_creator_review = FALSE) OR (author_kind = 'MEMBER' AND guest_ip_hmac IS NULL AND guest_ip_display IS NULL)),
  CHECK (is_creator_review = FALSE OR (author_kind = 'MEMBER' AND rating = 'NONE')),
  CHECK (visibility_status IN ('PUBLIC','TEMP_HIDDEN','HIDDEN')),
  UNIQUE (service_id, author_id),
  UNIQUE (reply_id),
  CHECK (reply_visibility_status IS NULL OR reply_visibility_status IN ('PUBLIC','TEMP_HIDDEN','HIDDEN')),
  CHECK ((reply_id IS NULL AND reply_author_id IS NULL AND reply_content IS NULL AND reply_visibility_status IS NULL AND reply_hidden_reason IS NULL AND reply_created_at IS NULL AND reply_updated_at IS NULL) OR (reply_id IS NOT NULL AND reply_content IS NOT NULL AND btrim(reply_content) <> '' AND reply_visibility_status IS NOT NULL AND reply_created_at IS NOT NULL AND reply_updated_at IS NOT NULL)),
  FOREIGN KEY (service_id) REFERENCES services (service_id) ON DELETE CASCADE,
  FOREIGN KEY (author_id) REFERENCES users (user_id) ON DELETE SET NULL,
  FOREIGN KEY (reply_author_id) REFERENCES users (user_id) ON DELETE SET NULL
);
COMMENT ON TABLE reviews IS '서비스 리뷰·평가';

## 2. 이용 목적

- 회원 식별, 로그인 유지, 계정 관리
- 서비스 등록·공개·검색·추천·순위 등 핵심 기능 제공
- 리뷰, 신고, 프로필 등 이용자 기능 운영
- 조회·이용 통계 제공과 서비스 품질 개선
- 신고 처리, 권리 침해 대응, 부정 이용 방지와 보안

## 3. 공개되는 정보

닉네임, 아이디, 프로필 사진, 한 줄 소개, 외부 링크, 등록한 서비스, 작성한 리뷰와 답글은 다른 이용자에게 표시될 수 있습니다. 익명 리뷰가 허용된 서비스에서 익명으로 작성한 리뷰는 작성자 표시가 가려집니다. 비회원 리뷰에는 IP 주소의 일부만 가려서 표시합니다. 이메일은 공개되지 않습니다.

## 4. 보유 및 삭제 (임시)

- 회원 정보는 탈퇴하면 삭제합니다. 등록한 서비스는 삭제되고, 작성한 리뷰는 "탈퇴한 사용자"로 표시된 채 유지될 수 있습니다.
- 신고·분쟁·보안 기록은 처리와 사고 대응에 필요한 기간 동안 보관합니다.
- 비회원 IP 해시와 이용 기록의 구체적인 보유 기간은 법적 확인 후 정합니다.

## 5. 쿠키와 세션

로그인 상태 유지, 보안, 이용 통계를 위해 쿠키와 이에 준하는 기술 정보를 사용합니다. 브라우저 설정으로 쿠키를 삭제하거나 제한할 수 있으나 일부 기능이 정상 동작하지 않을 수 있습니다.

## 6. 제3자 제공과 외부 서비스

- 로그인은 구글 소셜 로그인을 통해 이루어지며, 해당 서비스의 개인정보 처리방침이 적용됩니다.
- `이용하기` 등으로 외부 사이트나 GitHub로 이동하면 해당 서비스의 약관과 개인정보 처리방침이 적용됩니다.
- WEBTER는 이용자의 개인정보를 판매하지 않습니다.
- AI 자연어 검색을 도입하는 경우 검색어가 외부 AI 서비스로 전달될 수 있으며, 도입할 때 이 방침에 반영합니다.

## 7. 이용자의 권리

회원은 자신의 프로필과 등록한 서비스, 작성한 리뷰를 확인·수정·삭제할 수 있고, 탈퇴할 수 있습니다. 그 밖의 요청은 문의 이메일로 할 수 있습니다.

## 8. 아동의 개인정보

만 14세 미만은 회원으로 가입할 수 없습니다.

## 9. 보안

계정과 서비스 데이터에 대한 불필요한 접근을 제한하고, 세션 보호 등 운영에 필요한 보안 조치를 적용합니다. 보안 문제가 의심되면 공개 게시물이 아니라 문의 이메일로 알려 주세요.

## 10. 방침의 변경

서비스 기능이나 처리 방식이 바뀌면 이 방침이 변경될 수 있으며, 중요한 변경은 적용 전에 서비스 내에서 안내합니다.


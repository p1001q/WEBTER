## 제1조 목적

이 약관은 WEBTER(웹터)가 제공하는 웹 서비스 탐색·이용 연결, 회원 기능, 서비스 등록, 리뷰 등 서비스 이용에 필요한 기본 기준을 정합니다.

## 제2조 용어의 정의

- **서비스:** WEBTER가 제공하는 웹 서비스 탐색, 이용 연결, 리뷰·좋아요·저장, 서비스 등록·관리 등 관련 기능
- **이용자:** 로그인 여부와 관계없이 WEBTER를 이용하는 사람
- **회원:** 소셜 계정으로 로그인해 회원 기능을 이용하는 사람
- **등록자:** 자신이 만든 웹 서비스를 WEBTER에 등록한 회원
- **콘텐츠:** 등록자가 등록한 서비스 이름, 소개, 이미지, 링크 등과 이용자가 작성한 리뷰, 답글, 프로필 정보

## 제3조 서비스의 범위

WEBTER는 웹 서비스의 발견과 이용 연결을 중심으로 서비스를 제공합니다. WEBTER는 서비스를 직접 호스팅하지 않고, `이용하기`를 누르면 등록자가 제공하는 외부 사이트가 새 탭에서 열립니다. 일부 기능은 로그인이 필요하며, 서비스 단계에 따라 제공 범위가 달라질 수 있습니다.

## 제4조 회원 가입과 계정

- 회원은 소셜 로그인(구글)으로 가입하며, 만 14세 이상이어야 합니다.
- 회원은 아이디와 닉네임을 설정합니다. 타인을 사칭하거나 이용자를 오인하게 하는 방식으로 사용해서는 안 됩니다.
- 회원은 자신의 계정을 타인에게 부정하게 사용하도록 제공해서는 안 됩니다.
- 회원은 언제든지 탈퇴할 수 있으며, 탈퇴하면 등록한 서비스는 삭제되고 작성한 리뷰는 "탈퇴한 사용자"로 표시됩니다.

## 제5조 서비스 등록과 권리

- 등록한 서비스의 권리는 원칙적으로 등록자에게 있으며, WEBTER가 소유권을 취득하지 않습니다.
- 등록자는 직접 만들었거나 등록 권한이 있는 서비스만 등록해야 하며, 타인의 저작권·상표권·초상권·개인정보 등 권리를 침해해서는 안 됩니다.
- WEBTER는 서비스 제공을 위해 필요한 범위에서 등록된 서비스의 이름, 소개, 이미지 등을 목록·검색·추천·홍보(SNS 포함) 화면에 표시할 수 있습니다.
- 다음 서비스는 등록할 수 없습니다: 피싱·악성 사이트, 불법·사기·도박 서비스, 성인 콘텐츠 서비스, 타인의 권리를 침해하는 서비스.

## 제6조 리뷰와 반응

- 리뷰는 의견 글과 평가 상태(추천/비추천/미설정)로 이루어지며, 회원은 서비스당 하나를 작성할 수 있습니다.
- 등록자가 허용한 서비스에는 비회원도 평가 상태 없는 리뷰를 작성할 수 있습니다. 비회원 리뷰는 IP 주소로 같은 사람인지 구분하며, 수정할 수 없습니다.
- 리뷰에는 링크를 넣을 수 없습니다. 서비스 제작자는 리뷰에 답글을 달 수 있습니다.

## 제7조 금지되는 행위

- 악성 코드, 불법 정보, 이용자의 기기를 해칠 수 있는 콘텐츠를 게시·배포하는 행위
- 타인의 권리를 침해하거나 허위 정보, 사칭, 스팸으로 이용자를 오인하게 하는 행위
- 조회수, 좋아요, 이용 횟수, 순위 등 서비스 지표를 인위적으로 조작하는 행위
- 신고 기능을 악의적으로 반복 사용하거나 다른 이용자를 괴롭히는 행위
- 자동화된 비정상 요청, 취약점 악용 등 서비스 운영을 방해하는 행위

## 제8조 신고와 운영 조치

- 회원은 서비스, 리뷰, 답글, 프로필을 신고할 수 있습니다.
- 신고가 일정 수 이상 접수되거나 위반이 확인되면 WEBTER는 해당 콘텐츠를 임시 비공개하거나 노출을 제한하고, 비공개·삭제 등의 조치를 할 수 있습니다.
- 조치에 이의가 있으면 문의 이메일로 요청할 수 있습니다.

## 제9조 이용 제한

약관이나 운영 기준을 반복해서 위반하면 경고, 서비스 등록 제한, 계정 이용 제한 등의 조치를 할 수 있습니다. 위반 정도가 중대한 경우 사전 경고 없이 긴급한 조치를 할 수 있습니다.

## 제10조 외부 서비스와 링크

WEBTER에는 등록자가 제공하는 외부 사이트와 GitHub 저장소로 연결되는 기능이 있습니다. 외부 서비스의 운영, 약관, 개인정보 처리, 결제, 안전성은 해당 서비스 제공자의 기준이 적용되며, WEBTER는 이를 보증하지 않습니다. 서비스의 가격 정보는 등록자가 입력한 정보입니다.

## 제11조 광고와 수익 기능

WEBTER는 광고, 후원 등 수익 기능을 단계적으로 도입할 수 있습니다. 현재 제공되지 않는 기능은 이 약관만으로 이용할 수 있게 되지 않으며, 금전과 관련된 세부 기준은 도입할 때 별도로 고지합니다. 광고가 제공되는 경우 일반 순위와 광고를 구분하고 광고임을 표시합니다.

## 제12조 서비스의 변경·중단

서비스 개선, 점검, 장애 대응, 보안 등 운영상 필요한 경우 서비스의 전부 또는 일부를 변경하거나 일시 중단할 수 있으며, 중요한 변경은 서비스 내 공지로 안내합니다.

## 제13조 책임의 범위

WEBTER는 안정적이고 안전한 서비스 제공을 위해 노력하지만, 등록자가 등록한 서비스의 정확성·적법성·안전성과 이용자 간 별도 합의의 이행을 보증하지 않습니다. 합리적으로 통제하기 어려운 장애나 외부 서비스의 문제에 대해서는 관계 법령에서 정한 범위에서 책임집니다.

## 제14조 약관의 변경

서비스 구조, 법적 요구, 운영 정책이 바뀌면 약관이 변경될 수 있으며, 중요한 변경은 적용 전에 서비스 내에서 안내합니다.

## 제15조 준거법과 분쟁

이 약관과 서비스 이용에 관한 사항은 대한민국 관계 법령을 따릅니다.

